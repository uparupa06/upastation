#pragma once
#include <cstdint>
#include "utility.hpp"

constexpr uint8_t NUM_COP0_REGISTERS = 64;

class MIPS;

class COP0 {
public:

	COP0() {
		initialise();
	}

	// cop0.cpp
	void connect_mips(MIPS* mips);
	void initialise();

	// cop0_rw.cpp
	uint32_t read(uint32_t reg);
	void write(uint32_t reg, uint32_t value);
	
	// cop0_exception.cpp
	void handle_exception();
	uint32_t reset_exception_vector();
	uint32_t utlb_miss_exception_vector();
	uint32_t cop0_break_exception_vector();
	uint32_t general_exception_vector();

	// cop0_func.cpp
	void do_cofunc(uint32_t cofunc);

	// Basic accessors + exception raising functions
	void raise_INT_exception()  { set_ExcCode(0x00); handle_exception(); }  // External interrupt
	void raise_MOD_exception()  { set_ExcCode(0x01); handle_exception(); }  // TLB modification
	void raise_TLBL_exception() { set_ExcCode(0x02); handle_exception(); }  // TLB load
	void raise_TLBS_exception() { set_ExcCode(0x03); handle_exception(); }  // TLB store
	void raise_AdEL_exception() { set_ExcCode(0x04); handle_exception(); }  // Address error, data load or instruction fetch
	void raise_AdES_exception() { set_ExcCode(0x05); handle_exception(); }  // Address error, data store (attempts to read outside of KUseg in user mode/misaligned address)
	void raise_IBE_exception()  { set_ExcCode(0x06); handle_exception(); }  // Bus error on instruction fetch
	void raise_DBE_exception()  { set_ExcCode(0x07); handle_exception(); }  // Bus error on data load/store
	void raise_Sys_exception()  { set_ExcCode(0x08); handle_exception(); }  // Exception unconditionally generated by syscall instruction
	void raise_Bp_exception()   { set_ExcCode(0x09); handle_exception(); }  // Breakpoint
	void raise_RI_exception()   { set_ExcCode(0x0A); handle_exception(); }  // Reserved instruction
	void raise_CpU_exception()  { set_ExcCode(0x0B); handle_exception(); }  // Coprocessor unusable
	void raise_Ovf_exception()  { set_ExcCode(0x0C); handle_exception(); }  // Arithmetic overflow

	// cop0r6
	uint32_t get_TAR() { return TAR; }

	// cop0r7
	uint32_t DB()  { return extract_bits(DCIC, 0,  0); }
	uint32_t PC()  { return extract_bits(DCIC, 1,  1); }
	uint32_t DA()  { return extract_bits(DCIC, 2,  2); }
	uint32_t R()   { return extract_bits(DCIC, 3,  3); }
	uint32_t W()   { return extract_bits(DCIC, 4,  4); }
	uint32_t T()   { return extract_bits(DCIC, 5,  5); }
	uint32_t JR()  { return extract_bits(DCIC, 12, 13); } // using JR here to mean 'Jump redirection'
	uint32_t DE()  { return extract_bits(DCIC, 23, 23); }
	uint32_t PCE() { return extract_bits(DCIC, 24, 24); }
	uint32_t DAE() { return extract_bits(DCIC, 25, 25); }
	uint32_t DR()  { return extract_bits(DCIC, 26, 26); }
	uint32_t DW()  { return extract_bits(DCIC, 27, 27); }
	uint32_t TE()  { return extract_bits(DCIC, 28, 28); }
	uint32_t KD()  { return extract_bits(DCIC, 29, 29); }
	uint32_t UD()  { return extract_bits(DCIC, 30, 30); }
	uint32_t TR()  { return extract_bits(DCIC, 31, 31); }
	

	// cop0r12
	uint32_t IEc() { return extract_bits(SR, 0,  0); }
	uint32_t KUc() { return extract_bits(SR, 1,  1); }
	uint32_t IEp() { return extract_bits(SR, 2,  2); }
	uint32_t KUp() { return extract_bits(SR, 3,  3); }
	uint32_t IEo() { return extract_bits(SR, 4,  4); }
	uint32_t KUo() { return extract_bits(SR, 5,  5); }
	uint32_t Im()  { return extract_bits(SR, 8,  15); }
	uint32_t Isc() { return extract_bits(SR, 16, 16); }
	uint32_t Swc() { return extract_bits(SR, 17, 17); }
	uint32_t PZ()  { return extract_bits(SR, 18, 18); }
	uint32_t CM()  { return extract_bits(SR, 19, 19); }
	uint32_t PE()  { return extract_bits(SR, 20, 20); }
	uint32_t TS()  { return extract_bits(SR, 21, 21); }
	uint32_t BEV() { return extract_bits(SR, 22, 22); }
	uint32_t RE()  { return extract_bits(SR, 25, 25); }
	uint32_t CU0() { return extract_bits(SR, 28, 28); }
	uint32_t CU1() { return extract_bits(SR, 29, 29); }
	uint32_t CU2() { return extract_bits(SR, 30, 30); }
	uint32_t CU3() { return extract_bits(SR, 31, 31); }

	// cop0r13
	uint32_t ExcCode() { return extract_bits(CAUSE, 2, 6); }
	uint32_t Sw()      { return extract_bits(CAUSE, 8, 9); }
	uint32_t IP()      { return extract_bits(CAUSE, 10, 15); }
	uint32_t CE()      { return extract_bits(CAUSE, 28, 29); }
	uint32_t BT()      { return extract_bits(CAUSE, 30, 30); }
	uint32_t BD()      { return extract_bits(CAUSE, 31, 31); }

	// cop0r14
	uint32_t get_EPC() { return EPC; }

	// cop0r15
	uint32_t PRID_Revision()       { return extract_bits(PRID, 0, 7);  }
	uint32_t PRID_Implementation() { return extract_bits(PRID, 8, 15); }

	void set_BadA(uint32_t value) {
		BadA = value;
	}

	void set_ExcCode(uint8_t code) {
		CAUSE &= ~(0x7C);
		CAUSE |= ((code & 0x1F) << 2);
	}

	// For test handling
	void set_epc_tar_cause(uint32_t _epc, uint32_t _tar, uint32_t _cause) {
		EPC   = _epc;
		TAR   = _tar;
		CAUSE = _cause;
	}

	uint32_t get_CAUSE() {
		return CAUSE;
	}

private:

	MIPS* mips = nullptr;

	// Registers

	// R/W
	uint32_t r[NUM_COP0_REGISTERS];
	uint32_t& BPC   = r[3];  // cop0r3
	uint32_t& BDA   = r[5];  // cop0r5
	uint32_t& TAR   = r[6];  // cop0r6
	uint32_t& DCIC  = r[7];  // cop0r7
	uint32_t& BadA  = r[8];  // cop0r8
	uint32_t& BDAM  = r[9];  // cop0r9
	uint32_t& BPCM  = r[11]; // cop0r11
	uint32_t& SR    = r[12]; // cop0r12
	uint32_t& CAUSE = r[13]; // cop0r13
	uint32_t& EPC   = r[14]; // cop0r14
	uint32_t& PRID  = r[15]; // cop0r15
};
